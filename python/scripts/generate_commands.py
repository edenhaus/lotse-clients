"""Generates `src/lotse_client/_commands.py`: every command of the API as a typed method.

The bundle (`schema/api.json`) says everything a method needs: each command's
fields and their descriptions, the result type it is answered with (`results`)
and, for a subscribing command, its event type (`events`). The parameter types
and defaults are copied from the command classes datamodel-code-generator
wrote to `models.py`, so the methods and the models cannot disagree. A command
named `domain/verb` becomes the method `verb` of a `DomainCommands` namespace,
reached as `client.domain.verb(...)`; a command without a slash is a method of
the client itself. It also keeps `API_VERSION` in the hand-written
`version.py` at the bundle's `api`, so a version bump needs no hand-written
change.

Run it after `datamodel-codegen` (`mise run schema` runs both); `--check`
fails when the committed module or `API_VERSION` is stale (the `python-client`
hook).
"""

import argparse
import ast
import json
import keyword
import re
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path
from textwrap import TextWrapper
from typing import TYPE_CHECKING, Any, Self

if TYPE_CHECKING:
    from collections.abc import Callable

PYTHON = Path(__file__).resolve().parents[1]
"""The `python/` directory."""
BUNDLE = PYTHON.parent / "schema" / "api.json"
"""The API's JSON Schema bundle, copied from lotse."""
MODELS = PYTHON / "src" / "lotse_client" / "models.py"
"""The models datamodel-code-generator generated from the bundle."""
OUTPUT = PYTHON / "src" / "lotse_client" / "_commands.py"
"""The module this script writes."""
VERSION = PYTHON / "src" / "lotse_client" / "version.py"
"""The hand-written module whose `API_VERSION` this script keeps at the bundle's `api`."""
API_VERSION_LINE = re.compile(r'^API_VERSION = ".*"$', re.MULTILINE)
"""The one line of `version.py` this script rewrites."""

LINE_LENGTH = 100
"""ruff's line length (`pyproject.toml`), for the docstrings ruff does not wrap."""
INDENT = "    "
SUBSCRIBE_SIGNATURE = "(self, command: Model, events: BasicDecoder[E]) -> Subscription[E]"
"""The transport's `_subscribe`, after its type parameter."""

TYPING_NAMES = frozenset({"Any", "Annotated", "Literal"})
"""What `models.py` imports from `typing`, re-imported when an annotation uses it."""
BUILTIN_NAMES = frozenset({"bool", "dict", "float", "int", "list", "str", "None"})
"""What an annotation may name without an import."""

HEADER = '''"""Every command of the control API as a typed method.

Generated by `scripts/generate_commands.py` from `schema/api.json` and the
models datamodel-code-generator made from it. Do not edit: change the Rust
types in lotse, copy its bundle to `schema/`, then run `mise run schema` (or
`uv run python scripts/generate_commands.py` in `python/`).

A command named `domain/verb` is the method `verb` of the `domain` namespace
(`stream/put` is `client.stream.put`); one without a slash is a method of the
client. Each method builds the generated command class, sends it through the
transport and decodes the result the bundle names for it. A subscribing
command, one the bundle lists an event type for, returns a `Subscription` of
those events instead.
"""
'''


class GenerationError(Exception):
    """The bundle or the models say something this generator cannot turn into a method."""


@dataclass(frozen=True)
class Field:
    """One parameter of a method: a field of the command, as `models.py` typed it."""

    name: str
    annotation: str
    default: str | None
    """The default's source, `None` when the field is required."""
    description: str


@dataclass(frozen=True)
class Method:
    """One command as a method."""

    type: str
    """The wire name, `stream/put`."""
    namespace: str | None
    """`stream` for `stream/put`; `None` for a method of the client itself."""
    name: str
    """`put` for `stream/put`."""
    command_class: str
    """The generated command class, `StreamPutCommand`."""
    description: str
    fields: tuple[Field, ...]
    result: str | None
    """The model class the result decodes to, `None` when the result is empty."""
    raw_result: bool
    """The result is returned as the dict it came as (`schema`)."""
    event: str | None
    """The event type of a subscribing command."""

    @property
    def returns(self) -> str:
        """The method's return annotation."""
        if self.event is not None:
            return f"Subscription[{self.event}]"
        if self.raw_result:
            return "dict[str, Any]"
        return self.result or "None"


@dataclass(frozen=True)
class Models:
    """What `models.py` defines, read from its source."""

    classes: dict[str, ast.ClassDef]
    aliases: frozenset[str]

    @classmethod
    def parse(cls, source: str) -> Self:
        """Read the module's classes and `type` aliases."""
        module = ast.parse(source)
        classes = {node.name: node for node in module.body if isinstance(node, ast.ClassDef)}
        aliases = frozenset(node.name.id for node in module.body if isinstance(node, ast.TypeAlias))
        return cls(classes, aliases)

    def defines(self, name: str) -> bool:
        """Whether `name` is a class or an alias of the module."""
        return name in self.classes or name in self.aliases

    def fields(self, class_name: str) -> dict[str, tuple[str, str | None]]:
        """A class's fields: name to annotation source and default source."""
        try:
            node = self.classes[class_name]
        except KeyError:
            msg = f"models.py has no class {class_name}"
            raise GenerationError(msg) from None
        fields: dict[str, tuple[str, str | None]] = {}
        for statement in node.body:
            if isinstance(statement, ast.AnnAssign) and isinstance(statement.target, ast.Name):
                default = None if statement.value is None else ast.unparse(statement.value)
                fields[statement.target.id] = (ast.unparse(statement.annotation), default)
        return fields


def ref_name(schema: dict[str, Any]) -> str | None:
    """The `$defs` entry a schema refers to, `None` when it is not a reference."""
    ref = schema.get("$ref")
    return ref.removeprefix("#/$defs/") if isinstance(ref, str) else None


def resolve(bundle: dict[str, Any], schema: dict[str, Any]) -> dict[str, Any]:
    """The schema a reference points at."""
    name = ref_name(schema)
    if name is None:
        return schema
    definition = bundle["$defs"].get(name)
    if not isinstance(definition, dict):
        msg = f"the bundle has no definition {name}"
        raise GenerationError(msg)
    return definition


def result_of(bundle: dict[str, Any], command: str, models: Models) -> tuple[str | None, bool]:
    """The model class a command's result decodes to, and whether it is returned raw."""
    try:
        answer = resolve(bundle, bundle["results"][command])
    except KeyError:
        msg = f"the bundle names no result for {command}"
        raise GenerationError(msg) from None
    result = answer.get("properties", {}).get("result")
    if result is None:  # `pong`, which the transport answers with `{}`
        return None, False
    name = ref_name(result)
    if name is None:  # untyped, as `schema`'s bundle
        return None, True
    if name not in models.classes:
        msg = f"{command}'s result {name} is not a class in models.py"
        raise GenerationError(msg)
    if not models.fields(name):  # `Empty`
        return None, False
    return name, False


def event_of(bundle: dict[str, Any], command: str, models: Models) -> str | None:
    """The event type of a subscribing command, `None` for the others."""
    frame = bundle["events"].get(command)
    if frame is None:
        return None
    name = ref_name(resolve(bundle, frame).get("properties", {}).get("event", {}))
    if name is None or not models.defines(name):
        msg = f"{command}'s event type {name} is not defined in models.py"
        raise GenerationError(msg)
    return name


def method_of(bundle: dict[str, Any], variant: dict[str, Any], models: Models) -> Method:
    """One command variant of the bundle as a method."""
    command = variant["properties"]["type"]["const"]
    head, slash, tail = command.partition("/")
    namespace = head if slash else ""
    name = (tail if slash else head).replace("/", "_")  # `a/b/c` is `client.a.b_c`
    if keyword.iskeyword(name) or keyword.iskeyword(namespace):
        msg = f"{command} would be a method named after a Python keyword"
        raise GenerationError(msg)
    command_class = variant["title"]
    typed = models.fields(command_class)
    fields = []
    for field_name, schema in variant["properties"].items():
        if field_name in ("id", "type"):
            continue
        try:
            annotation, default = typed[field_name]
        except KeyError:
            msg = f"{command_class} in models.py has no field {field_name}"
            raise GenerationError(msg) from None
        fields.append(Field(field_name, annotation, default, schema.get("description", "")))
    fields.sort(key=lambda field: field.default is not None)  # required first, stably
    result, raw = result_of(bundle, command, models)
    return Method(
        type=command,
        namespace=namespace or None,
        name=name,
        command_class=command_class,
        description=variant.get("description", f"`{command}`."),
        fields=tuple(fields),
        result=result,
        raw_result=raw,
        event=event_of(bundle, command, models),
    )


def names_in(source: str) -> set[str]:
    """Every name an annotation or default expression uses."""
    return {node.id for node in ast.walk(ast.parse(source)) if isinstance(node, ast.Name)}


def pascal(snake: str) -> str:
    """`stream` to `Stream`, `metrics_get` to `MetricsGet`."""
    return "".join(part.capitalize() for part in snake.split("_"))


def upper_snake(camel: str) -> str:
    """`SessionEvent` to `SESSION_EVENT`."""
    return "".join(f"_{c}" if c.isupper() and i else c for i, c in enumerate(camel)).upper()


def paragraphs(description: str) -> list[str]:
    """A description's paragraphs, each on one line."""
    return [" ".join(block.split()) for block in description.split("\n\n") if block.strip()]


def split_summary(paragraph: str, width: int) -> tuple[str, str]:
    """The docstring's one-line summary and what of the first paragraph follows it.

    pydocstyle wants the summary on one line (D205): a paragraph that does not fit
    is cut after its first sentence, else its first clause, else the last comma
    that fits, else the backticked command name that opens it (`` `stream/put`: ``).
    ruff reports what still does not fit.
    """
    if len(paragraph) <= width:
        return paragraph, ""

    def cut(at: int, after: int) -> tuple[str, str]:
        rest = paragraph[at + after :]
        return f"{paragraph[:at]}.", rest[:1].upper() + rest[1:]

    for separator in (". ", "; "):
        at = paragraph.find(separator)
        if 0 < at < width:  # the summary gains a period
            return cut(at, len(separator))
    at = paragraph.rfind(", ", 0, width)
    if at > 0:
        return cut(at, len(", "))
    head, colon, _ = paragraph.partition(": ")
    if colon and head.startswith("`") and head.endswith("`") and len(head) < width:
        return cut(len(head), len(colon))
    return paragraph, ""


def docstring(description: str, fields: tuple[Field, ...], indent: str) -> list[str]:
    """A method's docstring: the description, then an `Args:` section for its fields."""
    width = LINE_LENGTH - len(indent)
    blocks = paragraphs(description)
    summary, rest = blocks[0], blocks[1:]
    if not summary.endswith((".", "!", "?", ":")):
        summary += "."
    summary, more = split_summary(summary, width - len('"""'))
    if more:
        rest.insert(0, more)
    lines = [f'{indent}"""{summary}']
    wrapper = TextWrapper(width=width, initial_indent=indent, subsequent_indent=indent)
    for block in rest:
        lines.append("")
        lines.extend(wrapper.wrap(block))
    if fields:
        lines.extend(("", f"{indent}Args:"))
        arg = TextWrapper(
            width=width, initial_indent=indent + INDENT, subsequent_indent=indent + INDENT * 2
        )
        for field in fields:
            text = " ".join(paragraphs(field.description)) or f"`{field.name}`."
            lines.extend(arg.wrap(f"{field.name}: {text}"))
    if len(lines) == 1:
        lines[0] += '"""'
    else:
        lines.append(f'{indent}"""')
    return lines


def method_source(method: Method, indent: str) -> list[str]:
    """One method's source lines, at `indent`."""
    params = ["self"]
    if method.fields:
        params.append("*")
        for field in method.fields:
            default = "" if field.default is None else f" = {field.default}"
            params.append(f"{field.name}: {field.annotation}{default}")
    lines = [f"{indent}async def {method.name}({', '.join(params)}) -> {method.returns}:"]
    lines.extend(docstring(method.description, method.fields, indent + INDENT))
    arguments = ", ".join(["id=NEW", *(f"{f.name}={f.name}" for f in method.fields)])
    lines.append(f"{indent + INDENT}command = {method.command_class}({arguments})")
    body = indent + INDENT
    if method.event is not None:
        lines.append(f"{body}return await self._subscribe(command, {upper_snake(method.event)}S)")
    elif method.raw_result:
        lines.append(f"{body}return await self._request(command)")
    elif method.result is not None:
        lines.append(f"{body}return {method.result}.from_dict(await self._request(command))")
    else:
        lines.append(f"{body}await self._request(command)")
    return lines


def namespace_source(namespace: str, methods: list[Method]) -> list[str]:
    """A namespace class holding the `domain/...` commands."""
    lines = [
        f"class {pascal(namespace)}Commands:",
        f'{INDENT}"""The `{namespace}/...` commands, as `client.{namespace}.<verb>(...)`."""',
        "",
        f"{INDENT}def __init__(self, request: Request, subscribe: Subscribe) -> None:",
        f'{INDENT * 2}"""Bind the transport\'s two primitives."""',
        f"{INDENT * 2}self._request = request",
        f"{INDENT * 2}self._subscribe = subscribe",
    ]
    for method in methods:
        lines.append("")
        lines.extend(method_source(method, INDENT))
    return lines


def commands_source(roots: list[Method], namespaces: dict[str, list[Method]]) -> list[str]:
    """The `Commands` base class: the namespaces, the primitives and the slash-less commands."""
    lines = [
        "class Commands(ABC):",
        f'{INDENT}"""Every command as a typed method or a namespace of them.',
        "",
        f"{INDENT}The transport implements the two primitives and calls `__init__`.",
        f'{INDENT}"""',
        "",
        f"{INDENT}def __init__(self) -> None:",
        f'{INDENT * 2}"""Bind every namespace to this transport."""',
    ]
    for namespace, methods in namespaces.items():
        verbs = ", ".join(f"`{m.type}`" for m in methods)
        binding = f"{pascal(namespace)}Commands(self._request, self._subscribe)"
        lines.append(f"{INDENT * 2}self.{namespace} = {binding}")
        lines.append(f'{INDENT * 2}"""{verbs}."""')
    lines.extend(
        (
            "",
            f"{INDENT}@abstractmethod",
            f"{INDENT}async def _request(self, command: Model) -> dict[str, Any]:",
            f'{INDENT * 2}"""Send `command`; return its `result`, or `{{}}` for `pong`."""',
            "",
            f"{INDENT}@abstractmethod",
            f"{INDENT}async def _subscribe[E]{SUBSCRIBE_SIGNATURE}:",
            f'{INDENT * 2}"""Send a subscribing `command`; decode its events with `events`."""',
        )
    )
    for method in roots:
        lines.append("")
        lines.extend(method_source(method, INDENT))
    return lines


def names_used(methods: list[Method], models: Models) -> tuple[list[str], list[str]]:
    """What the methods import: the names from `models.py`, and those from `typing`."""
    used: set[str] = set()
    for method in methods:
        used.add(method.command_class)
        used.update(filter(None, (method.result, method.event)))
        for field in method.fields:
            used.update(names_in(field.annotation))
            if field.default is not None:
                used.update(names_in(field.default))
    from_models = sorted(name for name in used if models.defines(name))
    unknown = used - set(from_models) - TYPING_NAMES - BUILTIN_NAMES
    if unknown:
        msg = f"annotations name {sorted(unknown)}, which models.py does not define"
        raise GenerationError(msg)
    return from_models, sorted({"TYPE_CHECKING", "Any", "Protocol", *(used & TYPING_NAMES)})


def grouped[K](methods: list[Method], key: Callable[[Method], K | None]) -> dict[K, list[Method]]:
    """The methods by `key`, in order of first appearance, leaving out those keyed `None`."""
    groups: dict[K, list[Method]] = {}
    for method in methods:
        group = key(method)
        if group is not None:
            groups.setdefault(group, []).append(method)
    return groups


def api_version(bundle: dict[str, Any]) -> str:
    """The API version the bundle describes (its `api`)."""
    version = bundle.get("api")
    if not isinstance(version, str):
        msg = "the bundle names no API version"
        raise GenerationError(msg)
    return version


def with_api_version(source: str, version: str) -> str:
    """`version.py`'s source with its `API_VERSION` set to `version`."""
    line = f"API_VERSION = {json.dumps(version)}"
    updated, count = API_VERSION_LINE.subn(lambda _: line, source)
    if count != 1:
        msg = f'version.py has {count} `API_VERSION = "..."` lines, not one'
        raise GenerationError(msg)
    return updated


def generate(bundle: dict[str, Any], models_source: str) -> str:
    """The module's source, formatted as ruff formats it."""
    models = Models.parse(models_source)
    variants = bundle["$defs"]["Command"]["oneOf"]
    methods = [method_of(bundle, variant, models) for variant in variants]
    roots = [m for m in methods if m.namespace is None]
    namespaces = grouped(methods, lambda m: m.namespace)
    decoders = grouped(methods, lambda m: m.event)
    from_models, typing = names_used(methods, models)

    lines = [
        HEADER,
        "from abc import ABC, abstractmethod",
        f"from typing import {', '.join(typing)}",
        "",
        "from mashumaro.codecs.basic import BasicDecoder",
        "",
        "from lotse_client.models import (",
        *(f"{INDENT}{name}," for name in from_models),
        ")",
        "",
        "if TYPE_CHECKING:",
        f"{INDENT}from collections.abc import Awaitable, Callable",
        "",
        f"{INDENT}from lotse_client._base import Model",
        f"{INDENT}from lotse_client.subscription import Subscription",
        "",
        "NEW = 0",
        '"""The `id` a method gives its command; the transport replaces it with the next id."""',
    ]
    for event, subscribing in decoders.items():
        commands = ", ".join(f"`{m.type}`" for m in subscribing)
        lines.extend(
            (
                "",
                f"{upper_snake(event)}S: BasicDecoder[{event}] = BasicDecoder({event})",
                f'"""Decodes the events of {commands}."""',
            )
        )
    lines.extend(
        (
            "",
            "type Request = Callable[[Model], Awaitable[dict[str, Any]]]",
            '"""The transport\'s `_request`: sends a command, returns its `result`."""',
            "",
            "",
            "class Subscribe(Protocol):",
            f'{INDENT}"""The transport\'s `_subscribe`: a subscribing command, its events."""',
            "",
            f"{INDENT}async def __call__[E]{SUBSCRIBE_SIGNATURE}: ...",
        )
    )
    for namespace, group in namespaces.items():
        lines.extend(("", ""))
        lines.extend(namespace_source(namespace, group))
    lines.extend(("", ""))
    lines.extend(commands_source(roots, namespaces))
    return ruff("\n".join(lines) + "\n")


def ruff(source: str) -> str:
    """`source` with its imports sorted and formatted by the ruff in the environment."""
    isort = ["check", "--select", "I", "--fix-only", "--quiet"]
    for arguments in (isort, ["format"]):
        completed = subprocess.run(
            [sys.executable, "-m", "ruff", *arguments, "--stdin-filename", str(OUTPUT), "-"],
            input=source,
            capture_output=True,
            text=True,
            check=False,
            cwd=PYTHON,
        )
        if completed.returncode != 0:
            msg = f"ruff {arguments[0]} failed: {completed.stderr.strip()}"
            raise GenerationError(msg)
        source = completed.stdout
    return source


def main(argv: list[str] | None = None) -> int:
    """Write the module and `API_VERSION`, or with `--check` report whether they are current."""
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n", 1)[0])
    parser.add_argument(
        "--check", action="store_true", help="fail instead of writing when the output is stale"
    )
    parser.add_argument("--bundle", type=Path, default=BUNDLE, help=argparse.SUPPRESS)
    parser.add_argument("--models", type=Path, default=MODELS, help=argparse.SUPPRESS)
    parser.add_argument("--output", type=Path, default=OUTPUT, help=argparse.SUPPRESS)
    parser.add_argument("--version-module", type=Path, default=VERSION, help=argparse.SUPPRESS)
    args = parser.parse_args(argv)
    try:
        bundle = json.loads(args.bundle.read_text())
        outputs = {
            args.output: generate(bundle, args.models.read_text()),
            args.version_module: with_api_version(
                args.version_module.read_text(), api_version(bundle)
            ),
        }
    except GenerationError as err:
        sys.stderr.write(f"{parser.prog}: {err}\n")
        return 2
    stale = [
        path
        for path, source in outputs.items()
        if (path.read_text() if path.exists() else None) != source
    ]
    if args.check:
        for path in stale:
            sys.stderr.write(f"{path} is stale: run `uv run python {parser.prog}`\n")
        return 1 if stale else 0
    for path in stale:
        path.write_text(outputs[path])
    return 0


if __name__ == "__main__":
    sys.exit(main())
